// 패턴 id → 세력 수준과 예상 되돌림 한계
function powerOf(patternId, opts = {}) {
  const p = POWER_BY_ID[patternId];
  if (!p) return null;
  const inTriangle = !!opts.insideTriangle;
  const power = inTriangle && p.triangleOverride != null ? p.triangleOverride : p.power;
  const abs = Math.abs(power);
  const retr = POWER_RETRACEMENT[abs] || POWER_RETRACEMENT[0];
  return {
    id: p.id,
    name: p.name,
    power,
    // 하락으로 완성됐으면 부호가 뒤집힌다
    effectivePower: opts.completedDown ? -power : power,
    maxRetracePct: retr.max,
    retraceDesc: retr.desc,
    nextImpulseMin: NEXT_IMPULSE_MIN[p.id] || null,
    note: p.note,
    group: p.group || null,
  };
}

// 플랫 변형 판정 — b/a 와 c/b 비율로 닐리의 변형 이름을 돌려준다
function classifyFlat(bOfA, cOfB, cOfA) {
  if (!(bOfA >= FLAT.entry.bMinOfA)) {
    return { ok: false, why: `파동 b가 파동 a의 ${(bOfA * 100).toFixed(1)}% — 최소 61.8%에 미달` };
  }
  if (cOfA != null && cOfA < FLAT.entry.cMinOfA) {
    return { ok: false, why: `파동 c가 파동 a의 ${(cOfA * 100).toFixed(1)}% — 최소 38.2%에 미달` };
  }
  const strength = FLAT.bStrength.find((s) => bOfA >= s.min && bOfA < s.max) ||
    FLAT.bStrength[FLAT.bStrength.length - 1];

  if (strength.id === 'strong') {
    if (bOfA <= 1.236) {
      if (cOfA != null && cOfA > 1.618) {
        return { ok: true, strength, id: 'elongatedFlat', name: '연장된 플랫' };
      }
      return { ok: true, strength, id: 'irregular', name: '불규칙 조정' };
    }
    if (bOfA <= 1.382) return { ok: true, strength, id: 'irregular', name: '불규칙 패턴' };
    // b > 138.2% — c가 b를 되돌릴 가능성 없음. 수평선 겹침 여부로 갈린다
    return {
      ok: true, strength, id: 'irregularFailure', name: '불규칙 미달형 또는 강세조정',
      needsHorizontalCheck: true,
      note: 'c가 수평선 구간과 겹치면 불규칙 미달형, 겹치지 않으면 강세조정',
    };
  }

  const table = FLAT.variants[strength.id];
  for (const v of table) {
    if (cOfB >= v.cOfB[0] && cOfB < v.cOfB[1]) {
      return { ok: true, strength, id: v.id, name: v.name };
    }
  }
  return { ok: true, strength, id: 'regularFlat', name: '일반적인 플랫' };
}

// 지그재그 변형 판정 — c/a 비율로
function classifyZigzag(cOfA) {
  for (const v of ZIGZAG.variants) {
    if (cOfA >= v.cOfA[0] && cOfA < v.cOfA[1]) return { ...v };
  }
  if (cOfA < 0.382) {
    return { id: null, name: '지그재그 아님', note: '파동 c가 파동 a의 38.2%에도 못 미친다' };
  }
  return ZIGZAG.variants[ZIGZAG.variants.length - 1];
}

