function checkSimilarity(priceA, priceB, barsA, barsB) {
  const pMin = Math.min(priceA, priceB);
  const pMax = Math.max(priceA, priceB);
  const tMin = Math.min(barsA, barsB);
  const tMax = Math.max(barsA, barsB);
  const priceOk = pMax > 0 && pMin / pMax >= SIMILARITY.priceRatio;
  const timeOk = tMax > 0 && tMin / tMax >= SIMILARITY.timeRatio;
  return {
    priceOk,
    timeOk,
    ok: priceOk || timeOk,
    priceRatio: pMax > 0 ? pMin / pMax : null,
    timeRatio: tMax > 0 ? tMin / tMax : null,
    why: priceOk || timeOk
      ? null
      : '가격·시간 유사성을 모두 충족하지 못했다 — 같은 등급이 아니므로 직접 연결할 수 없다',
  };
}

