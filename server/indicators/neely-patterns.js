// 부분 패턴 → 표 A 의 구조 표기
const COMBO_CODE = { zigzag: '5-3-5', flat: '3-3-5', triangle: '3-3-3-3-3(수렴만)' };

// x파동의 크기가 복합조정의 범주를 가른다. 이것이 세력 순위를 정하므로
// 복합조정에서 가장 중요한 한 가지 판정이다.
//   조건 1 · 작은 x파동 (≤61.8%)  → 범주 1 · 집약형 · 세력 +2
//   조건 2 · 큰 x파동  (≥161.8%) → 범주 2 · 확산형 · 세력 -3 (강세조정이면 +3)
// 그 사이 구간은 닐리가 정의하지 않았다 — 임의로 정하지 않고 미확정으로 남긴다.
function classifyXWave(xOfW) {
  if (xOfW <= 0.618) {
    return {
      size: 'small', category: 1, name: '작은 x파동',
      rule: XWAVE.cond1.rule, complexity: XWAVE.cond1.complexity,
      note: 'x파동이 작아 집약형이다 — 범주 1, 세력이 강한 복합조정',
    };
  }
  if (xOfW >= 1.618) {
    return {
      size: 'large', category: 2, name: '큰 x파동',
      rule: XWAVE.cond2.rule, complexity: XWAVE.cond2.complexity,
      note: 'x파동이 커 확산형이다 — 범주 2, 이후 충격파동의 최소 배수가 붙는다',
    };
  }
  return {
    size: 'ambiguous', category: null, name: 'x파동 크기 미확정',
    rule: `${pctText(xOfW)} 는 조건 1(≤61.8%)과 조건 2(≥161.8%) 사이다`,
    note: '닐리가 정의하지 않은 구간이다 — 범주를 확정하지 말고 양쪽 세력을 모두 남겨라',
  };
}

function pctText(r) {
  return `${(r * 100).toFixed(1)}%`;
}

// 부분 패턴 종류 배열(['zigzag','flat'] 등) → 표 A 의 이름과 세력 순위 id
// 표 A 는 첫 파동 기준으로만 적혀 있어 뒤집힌 조합이 없다. 순서를 무시하고 맞춘다.
function classifyCombo(kinds, xInfo) {
  const n = kinds.length; // 2 = 이중(W,Y) · 3 = 삼중(W,Y,Z)
  const codes = kinds.map((k) => COMBO_CODE[k] || k);
  const key = [...codes].sort().join('|');

  // 표 A 에서 같은 구성을 찾는다 (x 를 뺀 부분들만 비교)
  const tableName = (() => {
    for (const row of XWAVE.tableA) {
      const parts = row.parts.filter((p) => p !== 'x');
      if (parts.length !== n) continue;
      if ([...parts].sort().join('|') === key) return row.name;
    }
    return null;
  })();

  const allSame = codes.every((c) => c === codes[0]);
  const base = allSame
    ? (kinds[0] === 'zigzag' ? 'Zigzag' : kinds[0] === 'flat' ? 'Flat' : 'Combo')
    : 'Combo';
  const prefix = n >= 3 ? 'triple' : 'double';

  // 범주 2(큰 x파동)는 구조 이름과 무관하게 이중조정/삼중조정으로 묶인다.
  // 세력이 -3 으로 완전히 달라지므로 이 분기를 놓치면 안 된다.
  const cat2 = !!(xInfo && xInfo.category === 2);
  const id = cat2 ? (n >= 3 ? 'tripleThree' : 'doubleThree') : `${prefix}${base}`;

  const structName = tableName || (n >= 3 ? '삼중조합' : '이중조합');
  // 범주 2 는 이름 자체가 달라진다. 구성은 참고로만 괄호에 남긴다.
  const name = cat2
    ? `${n >= 3 ? '삼중조정' : '이중조정'} (${structName} 구성)`
    : structName;

  return {
    id,
    name,
    structName,
    codes,
    collapse: ':3', // 상위 등급에서는 조정파동 하나로 접힌다
    fromTable: !!tableName,
  };
}

